"""Fork audit 2: genre-confound check for c=0 candidate machine-text pools.

For each candidate pool, run roberta-base-openai-detector on PK-human vs
that pool, compute AUC, and compare to the Big5PersonalityEssays-machine
vs PK-human AUC as the same-genre benchmark.
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sklearn.metrics import roc_curve, auc  # noqa: E402
from detector.calibration import run_roberta_scores  # noqa: E402
from loaders.essays_loader import load as load_pk  # noqa: E402

SEED = 20260907
N_SAMPLE = 500


def sample(items, n, seed):
    rng = random.Random(seed)
    items = list(items)
    rng.shuffle(items)
    return items[:n]


def auc_for(human_texts, machine_texts):
    texts = human_texts + machine_texts
    y = [0] * len(human_texts) + [1] * len(machine_texts)
    scores = run_roberta_scores(texts)
    fpr, tpr, _ = roc_curve(y, scores)
    return float(auc(fpr, tpr))


def load_big5_machine():
    import openpyxl
    wb = openpyxl.load_workbook("data/big5_personality_essays/essays.xlsx", read_only=True, data_only=True)
    ws = wb["Foaie1"]
    out = []
    for i, row in enumerate(ws.iter_rows(values_only=True)):
        if i == 0 or row[0] is None:
            continue
        out.append(row[0])
    return out


def load_argugpt():
    from datasets import load_dataset
    d = load_dataset("SJTU-CL/ArguGPT", data_files={"train": "machine-train.csv"})
    return [r["text"] for r in d["train"]]


def load_ghostbuster_machine():
    from datasets import load_dataset
    d = load_dataset("polsci/ghostbuster-essay-cleaned")
    names = d["train"].features["label"].names
    human_idx = names.index("human")
    gptwriting_idx = names.index("gpt_writing")
    machine = [r["text"] for r in d["train"] if r["label"] == gptwriting_idx]
    return machine


def load_student_llm_machine():
    from datasets import load_dataset
    d = load_dataset("knarasi1/student_and_llm_essays")
    out = []
    for split in ("train", "test"):
        for ex in d[split]:
            t = ex["essay"]
            tail = t[-250:]
            if "generated by a Large Language Model" not in tail:
                continue
            m = t.find("Essay:")
            if m == -1:
                continue
            body = t[m + len("Essay:"):]
            cut = body.rfind("Determine if the essay")
            if cut != -1:
                body = body[:cut]
            body = body.strip()
            if len(body.split()) >= 20:
                out.append(body)
    return out


def main():
    pk = [r["text"] for r in load_pk()]
    pk_sample = sample(pk, N_SAMPLE, SEED)

    pools = {
        "big5_personality_essays_machine (benchmark)": load_big5_machine(),
        "argugpt_machine": load_argugpt(),
        "ghostbuster_gpt_writing_machine": load_ghostbuster_machine(),
        "student_llm_machine": load_student_llm_machine(),
    }

    results = {}
    for name, texts in pools.items():
        n = min(N_SAMPLE, len(texts))
        pool_sample = sample(texts, n, SEED + hash(name) % 1000)
        pk_this = sample(pk, n, SEED)  # matched n, same seed base
        a = auc_for(pk_this, pool_sample)
        results[name] = {"n_pool": len(texts), "n_used": n, "auc": a}
        print(f"{name}: n_pool={len(texts)} n_used={n} AUC={a:.4f}", file=sys.stderr)

    import json
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
