def att_pass(pi, c, kappa, delta, rel_H, rho_T, r_F, se, sp):
    """(E48) to (E51): survivor-sample attenuation, contamination + range restriction + manufactured gap."""
    pp = pop.pi_prime(pi, se, sp)
    st = pop.selection_stats(r_F, sp)
    q, lam = st.q, st.lam
    g = c * math.sqrt(kappa / rel_H)
    d_pass = delta + r_F * lam * math.sqrt(rel_H)
    N = (1 - pp) * q + pp * g + pp * (1 - pp) * r_F * lam * (r_F * lam + delta / math.sqrt(rel_H))
    D = (1 - pp) * (1 - rel_H * (1 - q)) + pp * kappa + pp * (1 - pp) * d_pass ** 2
    W = 1 - rho_T ** 2 * (1 - pp) * (1 - q) + pp * (1 - pp) * rho_T ** 2 * r_F ** 2 * lam ** 2
    return N / math.sqrt(D * W)


