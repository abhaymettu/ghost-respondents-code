def est(r: dict, name: str, target: str = "rho_H") -> dict:
    return r["estimators"][name][target]


def bias(r, name, target="rho_H"):
    return est(r, name, target)["bias"]


def rmse(r, name, target="rho_H"):
    return est(r, name, target)["rmse"]


def nz(x):
    return float("nan") if x is None else x


def cov(r, name, target="rho_H"):
    return nz(est(r, name, target)["coverage"])


def resolvable(r) -> bool:
    n = est(r, "naive")
    return abs(n["bias"]) > 2.0 * n["mcse"]


def meets_20(r, name) -> bool:
    return abs(bias(r, name)) <= 0.20 * abs(bias(r, "naive"))


def reduces(r, name) -> bool:
    return abs(bias(r, name)) < abs(bias(r, "naive"))


