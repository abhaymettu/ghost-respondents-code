def load(path: Path) -> list[dict]:
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def md_table(header: list[str], rows: list[list[object]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out) + "\n"


def f(x: float, d: int = 4) -> str:
    return "nan" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def pct(a: int, b: int) -> str:
    return f"{a}/{b} ({100.0 * a / b:.1f}%)"


def save(name: str, title: str, table: str, note: str = "") -> None:
    TABLES[name] = table
    body = f"<!-- generated by paper/scripts/make_tables.py; do not edit by hand -->\n# {title}\n\n{table}"
    if note:
        body += f"\n{note}\n"
    (OUT / f"{name}.md").write_text(body)


